"""Q3 counterfactual explainability: "what could have happened?"

Two strictly separated levels:

1. **Simulation** (`SandboxSimulator`): deterministic evaluation of a minimal
   alternative action against the *recorded pre-action state* (trace
   evidence). Produces a *predicted* outcome — never an executed claim.
2. **Controlled replay** (`ControlledReplayEngine`): the alternative is
   actually executed in an isolated clone of the synthetic environment,
   restored to the recorded pre-action balances. The replay is recorded
   explicitly (`ReplayRecord`) and kept separate from the traced execution.

Alternatives are generated by *minimal edits* to the observed action (clamp
the amount to the binding constraint; switch an unverified beneficiary to a
verified linked one). Externally supplied alternatives are also supported and
clearly marked as `provided`.

Uncertainty rubric (documented, deterministic):
    base 0.05
  + 0.30 if any compared requirement is UNKNOWN under simulation
  + 0.10 if the prediction was not validated by replay
  + 0.10 if beneficiary linkage was not observable in the recorded state
(clamped to 1.0)
"""

from __future__ import annotations

from dataclasses import dataclass

from ..banking.environment import BankEnvironment
from ..core.trace import ExecutionTrace
from ..requirements.model import ConstraintType, RequirementSet, load_requirements
from .decision import DecisionExplainer
from .matcher import TransferFacts, extract_facts
from .models import (
    ActionSpec,
    Counterfactual,
    CounterfactualExplanation,
    CounterfactualImpact,
    EvidenceItem,
    PredictedOutcome,
    ReplayRecord,
    RequirementComparisonItem,
    RequirementStatus,
)

_UNK = RequirementStatus.UNKNOWN
_SAT = RequirementStatus.SATISFIED
_VIOL = RequirementStatus.VIOLATED


# ----------------------------------------------------------------- simulator
class SandboxSimulator:
    """Deterministic 'what-if' evaluation against recorded state evidence."""

    name = "sandbox-simulator-v1"

    def simulate(
        self, alternative: ActionSpec, state: dict
    ) -> tuple[dict[str, RequirementStatus], str | None, bool | None, str | None]:
        """Return (requirement statuses by constraint, reason, success, state change)."""
        balances = state.get("balances") or {}
        limits = state.get("per_txn_limits") or {}
        verified = state.get("beneficiaries_verified") or {}
        links = state.get("linked_beneficiaries") or {}
        statuses = state.get("account_status") or {}

        account = alternative.account_id
        amount = alternative.amount_inr
        beneficiary = alternative.beneficiary_id

        # insufficient recorded state -> everything UNKNOWN (never assumed)
        if account not in balances or amount is None or beneficiary is None:
            unknowns = {c.value: _UNK for c in ConstraintType}
            return unknowns, None, None, None

        balance = balances.get(account)
        limit = limits.get(account)

        result: dict[str, RequirementStatus] = {}
        result[ConstraintType.AMOUNT_WITHIN_LIMIT.value] = (
            _UNK if limit is None else (_SAT if amount <= limit else _VIOL)
        )
        result[ConstraintType.BENEFICIARY_VERIFIED.value] = (
            _UNK if beneficiary not in verified
            else (_SAT if verified[beneficiary] else _VIOL)
        )
        result[ConstraintType.SUFFICIENT_BALANCE.value] = (
            _UNK if balance is None else (_SAT if balance >= amount else _VIOL)
        )

        # mirror the environment's documented check order for the reason code
        if statuses.get(account) not in (None, "ACTIVE"):
            reason, success = "ACCOUNT_NOT_ACTIVE", False
        elif amount <= 0:
            reason, success = "INVALID_AMOUNT", False
        elif beneficiary not in verified:
            reason, success = "BENEFICIARY_NOT_FOUND", False
        elif account in links and beneficiary not in links[account]:
            reason, success = "BENEFICIARY_NOT_LINKED", False
        elif not verified[beneficiary]:
            reason, success = "BENEFICIARY_UNVERIFIED", False
        elif limit is not None and amount > limit:
            reason, success = "LIMIT_EXCEEDED", False
        elif balance is not None and amount > balance:
            reason, success = "INSUFFICIENT_FUNDS", False
        else:
            reason, success = "OK", True

        if success and balance is not None:
            state_change = f"{account} balance {balance} -> {balance - amount}"
        else:
            state_change = "no state change (transfer rejected)"
        return result, reason, success, state_change


# -------------------------------------------------------------------- replay
class ControlledReplayEngine:
    """Executes an alternative action in an isolated synthetic sandbox."""

    name = "controlled-replay-engine-v1"

    def replay(self, alternative: ActionSpec, state_before: dict) -> ReplayRecord:
        env = BankEnvironment.from_dataset()
        env.restore_summary(state_before)
        before = env.summary()["balances"]
        out = env.transfer(alternative.beneficiary_id, alternative.amount_inr,
                           alternative.account_id)
        after = env.summary()["balances"]
        return ReplayRecord(
            performed=True,
            execution_success=bool(out["success"]),
            reason_code=out["reason_code"],
            state_change={"balances_before": before, "balances_after": after},
            transaction_id=out.get("transaction_id"),
            note=("Executed in an isolated clone of the synthetic environment "
                  "restored to the recorded pre-action balances; full ledger "
                  "history is not reconstructed."),
        )


# ----------------------------------------------------------------- generation
@dataclass
class _Candidate:
    action: ActionSpec
    changed_condition: str
    source: str  # "generated_minimal" | "provided"


def _generate_minimals(facts: TransferFacts, state: dict) -> list[_Candidate]:
    """Minimal edits toward the binding constraint; never unrelated actions."""
    if facts.invocation is None or facts.amount_inr is None:
        return []
    account = facts.account_id
    amount = facts.amount_inr
    beneficiary = facts.beneficiary_id
    limits = state.get("per_txn_limits") or {}
    balances = state.get("balances") or {}
    verified = state.get("beneficiaries_verified") or {}
    links = (state.get("linked_beneficiaries") or {}).get(account) or []

    limit = limits.get(account)
    balance = balances.get(account)
    candidates: list[_Candidate] = []

    def add(new_amount: int | None, new_beneficiary: str | None, condition: str) -> None:
        action = ActionSpec(tool="transfer", account_id=account,
                            beneficiary_id=new_beneficiary, amount_inr=new_amount)
        if action.amount_inr == amount and action.beneficiary_id == beneficiary:
            return  # no-op is not a counterfactual
        if any(c.action == action for c in candidates):
            return
        candidates.append(_Candidate(action, condition, "generated_minimal"))

    if limit is not None and amount > limit:
        add(limit, beneficiary,
            f"amount reduced from {amount} to the per-transaction limit {limit}")
    if balance is not None and amount > balance:
        add(balance, beneficiary,
            f"amount reduced from {amount} to the available balance {balance}")
    if limit is not None and balance is not None and amount > min(limit, balance):
        add(min(limit, balance), beneficiary,
            f"amount reduced from {amount} to the binding constraint "
            f"min(limit {limit}, balance {balance}) = {min(limit, balance)}")

    if beneficiary is not None and verified.get(beneficiary) is False:
        replacement = next(
            (b for b in links if b != beneficiary and verified.get(b) is True), None
        )
        if replacement is not None:
            add(amount, replacement,
                f"beneficiary switched from unverified {beneficiary} to verified "
                f"{replacement} (amount unchanged)")
    return candidates


# ------------------------------------------------------------------- explainer
class CounterfactualExplainer:
    """Q3 explainer: simulation + optional controlled replay (no LLM)."""

    name = "controlled-counterfactual-v1"

    UNCERTAINTY_BASE = 0.05
    PENALTY_UNKNOWN_REQUIREMENT = 0.30
    PENALTY_NO_REPLAY = 0.10
    PENALTY_LINKAGE_UNKNOWN = 0.10

    def __init__(
        self,
        decision_explainer: DecisionExplainer | None = None,
        requirements: RequirementSet | None = None,
        replay_enabled: bool = True,
    ) -> None:
        self._decision = decision_explainer or DecisionExplainer(
            requirements=requirements
        )
        self._requirements = requirements or self._decision.requirements or load_requirements()
        self._simulator = SandboxSimulator()
        self._replay_engine = ControlledReplayEngine() if replay_enabled else None

    def explain(
        self, trace: ExecutionTrace, alternatives: list[ActionSpec] | None = None
    ) -> CounterfactualExplanation:
        facts = extract_facts(trace)
        decision = self._decision.explain(trace)
        notes: list[str] = []

        if facts.invocation is None:
            return CounterfactualExplanation(
                task_id=trace.task_id, trace_id=trace.trace_id,
                task_text=trace.task_text, agent_id=trace.agent_id,
                action=facts.action or "UNKNOWN",
                actual_summary="No banking action was observed in this trace.",
                notes=["No action observed: counterfactuals cannot be generated."],
                llm_used=False,
            )

        state = facts.invocation.state_before or {}
        actual = self._original_action(facts)
        actual_success, _actual_code = trace.final_outcome

        generated = _generate_minimals(facts, state)
        candidates = list(generated)
        for alt in alternatives or []:
            resolved = ActionSpec(
                tool=alt.tool,
                account_id=alt.account_id or facts.account_id,
                beneficiary_id=alt.beneficiary_id,
                amount_inr=alt.amount_inr,
            )
            if resolved == actual:
                notes.append("Provided alternative equals the original action; skipped.")
                continue
            if resolved.amount_inr is None or resolved.beneficiary_id is None:
                notes.append("Provided alternative is incomplete (needs amount and "
                             "beneficiary); skipped.")
                continue
            candidates.append(
                _Candidate(resolved, "user-provided alternative action", "provided"))

        if not state:
            notes.append("No recorded pre-action state: alternatives cannot be "
                         "simulated against evidence.")
        if not generated and state:
            notes.append("No minimal alternative differs from the original action "
                         "(nothing to improve).")

        actual_statuses = {a.requirement_id: a.status for a in decision.requirements}
        counterfactuals = [
            self._build_counterfactual(
                n, candidate, facts, state, actual_statuses,
                actual_success, notes,
            )
            for n, candidate in enumerate(candidates, start=1)
        ]

        actual_summary = self._summarize_actual(facts, decision, actual_success)
        return CounterfactualExplanation(
            task_id=trace.task_id, trace_id=trace.trace_id,
            task_text=trace.task_text, agent_id=trace.agent_id,
            action=facts.action or "UNKNOWN",
            actual_summary=actual_summary,
            counterfactuals=counterfactuals,
            notes=notes,
            llm_used=False,
        )

    # ------------------------------------------------------------ internals
    @staticmethod
    def _original_action(facts: TransferFacts) -> ActionSpec:
        return ActionSpec(
            tool="transfer", account_id=facts.account_id,
            beneficiary_id=facts.beneficiary_id, amount_inr=facts.amount_inr,
        )

    def _build_counterfactual(
        self, index: int, candidate: _Candidate, facts: TransferFacts,
        state: dict, actual_statuses: dict | None, actual_success: bool | None,
        notes: list[str],
    ) -> Counterfactual:
        statuses, reason, success, state_change = self._simulator.simulate(
            candidate.action, state
        )
        comparison = self._compare(statuses, actual_statuses or {})

        replay: ReplayRecord | None = None
        if self._replay_engine is not None and state:
            replay = self._replay_engine.replay(candidate.action, state)
        elif self._replay_engine is None:
            notes.append(f"{candidate.source} alternative: replay disabled; "
                         f"prediction not validated by execution.")
        else:
            notes.append(f"{candidate.source} alternative: replay unavailable "
                         f"(no recorded pre-action state).")

        uncertainty = self._uncertainty(statuses, replay, state)
        evidence = self._evidence(facts, candidate, state)
        impact = self._impact(actual_success, success)
        explanation = self._explain(candidate, statuses, reason, success,
                                    state_change, comparison, replay)
        return Counterfactual(
            cf_id=f"CF-{index:04d}",
            source=candidate.source,
            original_action=self._original_action(facts),
            alternative_action=candidate.action,
            changed_condition=candidate.changed_condition,
            predicted_outcome=PredictedOutcome(
                success=success, reason_code=reason,
                requirement_statuses=statuses,
                expected_state_change=state_change,
            ),
            replay=replay,
            requirement_comparison=comparison,
            evidence=evidence,
            impact=impact,
            uncertainty=round(min(1.0, uncertainty), 2),
            explanation=explanation,
        )

    def _compare(
        self, alternative: dict[str, RequirementStatus],
        actual: dict[str, RequirementStatus],
    ) -> list[RequirementComparisonItem]:
        items = []
        for requirement in self._requirements.applicable_to("TRANSFER"):
            alt_status = alternative.get(requirement.constraint.type.value, _UNK)
            act_status = actual.get(requirement.id, _UNK)
            items.append(RequirementComparisonItem(
                requirement_id=requirement.id,
                actual_status=act_status,
                alternative_status=alt_status,
                changed=act_status is not alt_status,
            ))
        return items

    def _uncertainty(
        self, statuses: dict[str, RequirementStatus],
        replay: ReplayRecord | None, state: dict,
    ) -> float:
        value = self.UNCERTAINTY_BASE
        if any(s is _UNK for s in statuses.values()):
            value += self.PENALTY_UNKNOWN_REQUIREMENT
        if replay is None or not replay.performed:
            value += self.PENALTY_NO_REPLAY
        if "linked_beneficiaries" not in state:
            value += self.PENALTY_LINKAGE_UNKNOWN
        return value

    def _evidence(
        self, facts: TransferFacts, candidate: _Candidate, state: dict
    ) -> list[EvidenceItem]:
        event_id = facts.invocation.event_id
        account = facts.account_id
        items = [
            EvidenceItem(event_id=event_id, field="tool_input.amount_inr",
                         value=facts.amount_inr),
        ]
        if facts.beneficiary_id is not None:
            items.append(EvidenceItem(
                event_id=event_id, field="tool_input.beneficiary_id",
                value=facts.beneficiary_id))
        limits = state.get("per_txn_limits") or {}
        balances = state.get("balances") or {}
        verified = state.get("beneficiaries_verified") or {}
        if account in limits:
            items.append(EvidenceItem(
                event_id=event_id, field=f"state_before.per_txn_limits.{account}",
                value=limits[account]))
        if account in balances:
            items.append(EvidenceItem(
                event_id=event_id, field=f"state_before.balances.{account}",
                value=balances[account]))
        for beneficiary in {facts.beneficiary_id, candidate.action.beneficiary_id}:
            if beneficiary in verified:
                items.append(EvidenceItem(
                    event_id=event_id,
                    field=f"state_before.beneficiaries_verified.{beneficiary}",
                    value=verified[beneficiary]))
        return items

    @staticmethod
    def _impact(actual_success: bool | None, predicted_success: bool | None) -> CounterfactualImpact:
        if actual_success is None or predicted_success is None:
            return CounterfactualImpact.UNKNOWN
        if predicted_success and not actual_success:
            return CounterfactualImpact.IMPROVES
        if actual_success and not predicted_success:
            return CounterfactualImpact.WORSENS
        return CounterfactualImpact.UNCHANGED

    def _explain(
        self, candidate: _Candidate, statuses: dict[str, RequirementStatus],
        reason: str | None, success: bool | None, state_change: str | None,
        comparison: list[RequirementComparisonItem], replay: ReplayRecord | None,
    ) -> str:
        if success is None:
            base = (f"Alternative ({candidate.changed_condition}): outcome cannot be "
                    f"determined from the recorded evidence.")
        elif success:
            base = (f"Alternative ({candidate.changed_condition}): the transfer would "
                    f"have succeeded; {state_change}.")
        else:
            violated = [c.requirement_id for c in comparison
                        if c.alternative_status is _VIOL]
            detail = (f"requirement(s) {', '.join(violated)} remain VIOLATED"
                      if violated else "no registered requirement explains the rejection")
            base = (f"Alternative ({candidate.changed_condition}): the transfer would "
                    f"still have been rejected with {reason} ({detail}).")

        changed = [c.requirement_id for c in comparison if c.changed]
        if changed:
            base += f" Requirement status changes: {', '.join(changed)}."
        if replay is not None and replay.performed:
            base += (f" Controlled replay confirmed: {replay.reason_code} "
                     f"({replay.note.split(';')[0].lower()}).")
        elif replay is None:
            base += " Not replayed: prediction only, no execution claim is made."
        return base

    @staticmethod
    def _summarize_actual(facts: TransferFacts, decision, actual_success: bool | None) -> str:
        violations = [
            a.requirement_id for a in decision.requirements
            if a.status is RequirementStatus.VIOLATED
        ]
        outcome = ("succeeded" if actual_success
                   else "was rejected" if actual_success is False else "has unknown outcome")
        detail = (f"violating {', '.join(violations)}" if violations
                  else "with no recorded requirement violation")
        return (f"Actual transfer of INR {facts.amount_inr} to {facts.beneficiary_id} "
                f"{outcome} {detail}.")
